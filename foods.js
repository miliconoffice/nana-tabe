// 时段判断
function getPeriod() {
  const h = new Date().getHours();
  if (h >= 6 && h < 10) return "早餐";
  if (h >= 10 && h < 14) return "午餐";
  if (h >= 14 && h < 17) return "下午茶";
  if (h >= 17 && h < 21) return "晚餐";
  return "夜宵";
}

